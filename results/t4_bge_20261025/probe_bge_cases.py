def first_rank(ids, gold):
    return next((index for index, chunk_id in enumerate(ids, 1) if chunk_id == gold), None)


def main():
    retrievers = T4Retrievers(dense_backend="bge")
    rows = []
    for query_id, question, gold in PROBES:
        sparse = [d.metadata["chunk_id"] for d in retrievers.search(question, "bm25", 10)]
        dense = [d.metadata["chunk_id"] for d in retrievers.search(question, "dense", 10)]
        rows.append({"id": query_id, "question": question, "gold_chunk_id": gold,
                     "bm25_rank": first_rank(sparse, gold), "bge_rank": first_rank(dense, gold),
                     "bm25_top10": sparse, "bge_top10": dense})
    output = Path(__file__).with_name("t4_bge_candidate_probe.json")
    output.write_text(json.dumps(rows, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    for row in rows:
        print(row["id"], row["bm25_rank"], row["bge_rank"], row["question"])
    print(f"保存至 {output}")


if __name__ == "__main__":
    main()
