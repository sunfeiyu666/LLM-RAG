def main():
    out=ROOT/'results/t7'
    answers={r['id']:r for r in read_jsonl(ROOT/'data/system_answers.jsonl')}
    qs={r['id']:r for r in read_jsonl(ROOT/'data/eval/qa_set.jsonl')}
    assert set(RUBRICS)==set(qs)
    rows=[]
    for qid,criteria in RUBRICS.items():
        assert sum(c[1] for c in criteria)==5
        rows.append({'id':qid,'score':sum(c[0] for c in criteria),'max_score':5,
            'criteria':[dict(zip(['awarded','available','criterion','observation'],c)) for c in criteria],
            'reviewer':'Codex assistant; explicit question/reference/source review; not independent human',
            'answer_sha256':hashlib.sha256(answers[qid]['answer'].encode()).hexdigest(),
            'note':'Question-specific checklist and factual-detail deductions; published after inspecting outputs, not preregistered. Raw model grading retained separately.'})
    (out/'correctness_reviewed.json').write_text(json.dumps(rows,ensure_ascii=False,indent=2),encoding='utf-8')
    print('CORRECTNESS_REVIEW_COMPLETE',len(rows),'mean',sum(r['score'] for r in rows)/len(rows))

if __name__=='__main__':main()
