def literal_quote(text,anchor):
    positions=[i for i,c in enumerate(text) if not c.isspace()]
    compact=''.join(text[i] for i in positions);needle=''.join(anchor.split())
    start=compact.find(needle)
    assert start>=0,anchor
    begin=positions[start];end=positions[start+len(needle)-1]+1
    # Expand to a nearby original sentence/line while preserving literal bytes.
    left=max(text.rfind(mark,0,begin)+len(mark) for mark in ['\n','。','；'])
    stops=[p for mark in ['\n','。','；'] if (p:=text.find(mark,end))>=0]
    right=min(stops)+1 if stops else len(text)
    if begin-left>100:left=begin
    if right-end>180:right=end
    return text[left:right].strip()

